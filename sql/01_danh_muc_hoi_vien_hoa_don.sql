--1. BẢNG DANH MỤC
CREATE TABLE HANG_HOI_VIEN (
    MaHang VARCHAR(10) CONSTRAINT PK_HANG_HOI_VIEN PRIMARY KEY,
    TenHang NVARCHAR(50) NOT NULL CONSTRAINT UQ_HANG_TenHang UNIQUE,
    NguongChiTieuToiThieu DECIMAL(18,2) NOT NULL CONSTRAINT DF_HANG_Nguong DEFAULT 0,
    CONSTRAINT CK_HANG_Nguong CHECK (NguongChiTieuToiThieu >= 0)
);

CREATE TABLE CHI_NHANH (
    MaCN VARCHAR(10) CONSTRAINT PK_CHI_NHANH PRIMARY KEY,
    TenCN NVARCHAR(100) NOT NULL
);

CREATE TABLE NHAN_VIEN (
    MaNV VARCHAR(10) CONSTRAINT PK_NHAN_VIEN PRIMARY KEY,
    TenNV NVARCHAR(100) NOT NULL
);

CREATE TABLE SAN_PHAM (
    MaSP VARCHAR(10) CONSTRAINT PK_SAN_PHAM PRIMARY KEY,
    TenSP NVARCHAR(150) NOT NULL,
    Loai NVARCHAR(50) NULL,
    GiaBan DECIMAL(18,2) NOT NULL,
    MucTonToiThieu INT NOT NULL CONSTRAINT DF_SP_MucTon DEFAULT 0,
    CONSTRAINT CK_SP_GiaBan CHECK (GiaBan >= 0),
    CONSTRAINT CK_SP_MucTon CHECK (MucTonToiThieu >= 0)
);

CREATE TABLE GOI_DICH_VU (
    MaGoi VARCHAR(10) CONSTRAINT PK_GOI_DICH_VU PRIMARY KEY,
    TenGoi NVARCHAR(150)  NOT NULL,
    Loai NVARCHAR(50) NULL,
    ThoiHanThang INT NOT NULL,
    SoBuoiPT INT NOT NULL CONSTRAINT DF_GOI_SoBuoiPT DEFAULT 0,
    GiaTien DECIMAL(18,2)  NOT NULL,
    CONSTRAINT CK_GOI_ThoiHan CHECK (ThoiHanThang > 0),
    CONSTRAINT CK_GOI_SoBuoi  CHECK (SoBuoiPT >= 0),
    CONSTRAINT CK_GOI_GiaTien CHECK (GiaTien >= 0)
);
GO


--2. HOI_VIEN  (có cột tích lũy phục vụ Loyalty - CSDLNC-27)
CREATE TABLE HOI_VIEN (
    MaHV VARCHAR(10) CONSTRAINT PK_HOI_VIEN PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    SDT VARCHAR(15) NOT NULL CONSTRAINT UQ_HV_SDT UNIQUE,
    Email VARCHAR(150) NULL,
    CCCD VARCHAR(20) NULL,
    GioiTinh NVARCHAR(10) NULL,
    NgaySinh DATE NULL,
    NgayDangKy DATE NOT NULL CONSTRAINT DF_HV_NgayDK DEFAULT CAST(GETDATE() AS DATE),
    -- Cột tích lũy: cộng dồn trực tiếp khi thanh toán, tránh quét lại hóa đơn 12 tháng
    TongChiTieuNam  DECIMAL(18,2)  NOT NULL CONSTRAINT DF_HV_ChiTieu DEFAULT 0,
    DiemLoyalty INT NOT NULL CONSTRAINT DF_HV_Diem DEFAULT 0,
    MaHang VARCHAR(10) NULL,
    CONSTRAINT FK_HV_Hang FOREIGN KEY (MaHang) REFERENCES HANG_HOI_VIEN(MaHang),
    CONSTRAINT CK_HV_ChiTieu CHECK (TongChiTieuNam >= 0),
    CONSTRAINT CK_HV_Diem CHECK (DiemLoyalty >= 0)
);
CREATE INDEX IX_HV_MaHang ON HOI_VIEN(MaHang);
GO


--3. TON_KHO  (PK kép: chi nhánh + sản phẩm)

CREATE TABLE TON_KHO (
    MaCN VARCHAR(10) NOT NULL,
    MaSP VARCHAR(10) NOT NULL,
    SoLuongTon INT NOT NULL CONSTRAINT DF_TK_SL DEFAULT 0,
    CONSTRAINT PK_TON_KHO PRIMARY KEY (MaCN, MaSP),
    CONSTRAINT FK_TK_CN FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT FK_TK_SP FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP),
    CONSTRAINT CK_TK_SL CHECK (SoLuongTon >= 0)
);
GO


--4. HOA_DON & CHI_TIET_HOA_DON

CREATE TABLE HOA_DON (
    MaHD VARCHAR(15) CONSTRAINT PK_HOA_DON PRIMARY KEY,
    NgayLap DATETIME2(0) NOT NULL CONSTRAINT DF_HD_NgayLap DEFAULT SYSDATETIME(),
    MaCN VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    MaHV VARCHAR(10) NULL,          -- NULL = khách lẻ, không phải hội viên
    TongTien DECIMAL(18,2) NOT NULL CONSTRAINT DF_HD_TongTien DEFAULT 0,
    GiamGia DECIMAL(18,2) NOT NULL CONSTRAINT DF_HD_GiamGia DEFAULT 0,
    HinhThucTT NVARCHAR(30) NULL,
    CONSTRAINT FK_HD_CN FOREIGN KEY (MaCN) REFERENCES CHI_NHANH(MaCN),
    CONSTRAINT FK_HD_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT FK_HD_HV FOREIGN KEY (MaHV) REFERENCES HOI_VIEN(MaHV),
    CONSTRAINT CK_HD_TongTien CHECK (TongTien >= 0),
    CONSTRAINT CK_HD_GiamGia  CHECK (GiamGia >= 0)
);

CREATE TABLE CHI_TIET_HOA_DON (
    MaHD VARCHAR(15) NOT NULL,
    Dong INT NOT NULL,
    MaGoi VARCHAR(10) NULL,
    MaSP VARCHAR(10) NULL,
    SoLuong INT NOT NULL,
    DonGia DECIMAL(18,2) NOT NULL,
    ThanhTien DECIMAL(18,2) NOT NULL,
    NgayLap DATETIME2(0)  NOT NULL,   -- phi chuẩn hóa từ HOA_DON để lọc theo ngày không cần JOIN
    CONSTRAINT PK_CTHD PRIMARY KEY (MaHD, Dong),
    CONSTRAINT FK_CTHD_HD FOREIGN KEY (MaHD) REFERENCES HOA_DON(MaHD),
    CONSTRAINT FK_CTHD_Goi FOREIGN KEY (MaGoi) REFERENCES GOI_DICH_VU(MaGoi),
    CONSTRAINT FK_CTHD_SP FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP),
    CONSTRAINT CK_CTHD_SL CHECK (SoLuong > 0),
    CONSTRAINT CK_CTHD_DonGia CHECK (DonGia >= 0),
    CONSTRAINT CK_CTHD_ThanhTien CHECK (ThanhTien = SoLuong * DonGia),
    -- Mỗi dòng chỉ là MỘT trong hai: gói dịch vụ HOẶC sản phẩm
    CONSTRAINT CK_CTHD_GoiHoacSP CHECK (
        (MaGoi IS NOT NULL AND MaSP IS NULL) OR (MaGoi IS NULL AND MaSP IS NOT NULL)
    )
);
GO


--5. LICH_SU_DIEM

CREATE TABLE LICH_SU_DIEM (
    MaLS VARCHAR(20) CONSTRAINT PK_LICH_SU_DIEM PRIMARY KEY,
    MaHV VARCHAR(10) NOT NULL,
    MaHD VARCHAR(15) NULL,
    DiemCong INT NOT NULL,
    ThoiDiem DATETIME2(0) NOT NULL CONSTRAINT DF_LSD_ThoiDiem DEFAULT SYSDATETIME(),
    CONSTRAINT FK_LSD_HV FOREIGN KEY (MaHV) REFERENCES HOI_VIEN(MaHV),
    CONSTRAINT FK_LSD_HD FOREIGN KEY (MaHD) REFERENCES HOA_DON(MaHD)
);
GO

--6. INDEX hỗ trợ truy vấn / báo cáo

-- Báo cáo theo thời gian + chi nhánh
CREATE INDEX IX_HD_NgayLap_CN ON HOA_DON(NgayLap, MaCN) INCLUDE (TongTien, GiamGia);
-- Tra cứu hóa đơn theo hội viên (xét hạng, lịch sử mua)
CREATE INDEX IX_HD_MaHV       ON HOA_DON(MaHV) INCLUDE (NgayLap, TongTien);
CREATE INDEX IX_HD_MaCN       ON HOA_DON(MaCN);
-- Gói/SP bán chạy
CREATE INDEX IX_CTHD_Goi_Ngay ON CHI_TIET_HOA_DON(MaGoi, NgayLap) INCLUDE (SoLuong, ThanhTien) WHERE MaGoi IS NOT NULL;
CREATE INDEX IX_CTHD_SP_Ngay  ON CHI_TIET_HOA_DON(MaSP, NgayLap)  INCLUDE (SoLuong, ThanhTien) WHERE MaSP  IS NOT NULL;
-- Lịch sử điểm
CREATE INDEX IX_LSD_MaHV      ON LICH_SU_DIEM(MaHV, ThoiDiem);
CREATE INDEX IX_LSD_MaHD      ON LICH_SU_DIEM(MaHD) WHERE MaHD IS NOT NULL;
GO
